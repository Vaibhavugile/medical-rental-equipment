function Physioreadmore() {
  const [visiblePages, setVisiblePages] = useState(1);

  const showMore = () => {
    setVisiblePages((prev) => Math.min(prev + 1, pages.length));
  };

  const showLess = () => {
    setVisiblePages(1);

    window.scrollTo({
      top: 0,
      behavior: "smooth",
    });
  };

  return (
    <div className="app">
      <div className="document">

        {pages.slice(0, visiblePages).map((page, index) => (
          <div className="page" key={index}>

            <div className="page-header">
              <div className="logo">
                BookMyMedicare
              </div>

              <div className="page-number">
                Page {index + 1}
              </div>
            </div>

            <div className="page-content">

              <h1>{page.title}</h1>

              <div className="heading-line"></div>

              <div className="content-text">
  {page.content
    .trim()
    .split("\n\n")
    .map((paragraph, i) => (
      <p
        key={i}
        dangerouslySetInnerHTML={{
          __html: paragraph.trim(),
        }}
      />
    ))}
</div>
            </div>

            <div className="page-footer">
              <span>BookMyMedicare</span>
              <span>{index + 1}</span>
            </div>

          </div>
        ))}

        <div className="buttons">

          {visiblePages < pages.length && (
            <button
              className="show-more"
              onClick={showMore}
            >
              Show More
            </button>
          )}

          {visiblePages > 1 && (
            <button
              className="show-less"
              onClick={showLess}
            >
              Show Less
            </button>
          )}

        </div>

      </div>
    </div>
  );
}

export default Physioreadmore;